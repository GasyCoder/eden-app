export function currentLocale() {
    return usePage().props.locale === 'en' ? 'en' : 'fr';
}

/** t('key') ou t('key', arg1, arg2) pour les messages paramétrés. */
export function useT() {
    const page = usePage();
    const locale = computed(() => (page.props.locale === 'en' ? 'en' : 'fr'));

    const t = (key, ...args) => {
        const message = MESSAGES[locale.value][key] ?? MESSAGES.fr[key] ?? key;

        return typeof message === 'function' ? message(...args) : message;
    };

    const path = (name, slug = null) => {
        const base = PATHS[locale.value][name] ?? PATHS.fr[name] ?? '/';

        return slug ? `${base}/${slug}` : base;
    };

    return { t, path, locale };
}

const dateLocale = (locale) => (locale === 'en' ? 'en-GB' : 'fr-FR');

export function formatDate(iso, locale = 'fr', options = { day: 'numeric', month: 'long', year: 'numeric' }) {
    if (!iso) {
        return '';
    }

    return new Intl.DateTimeFormat(dateLocale(locale), { timeZone: EDITORIAL_TIMEZONE, ...options }).format(new Date(iso));
}

export function formatTime(iso, locale = 'fr') {
    return formatDate(iso, locale, { hour: '2-digit', minute: '2-digit' });
}

/** Plage lisible : « 12 nov. 2026, 09:00 à 12:00 » ou « 12 nov. 2026 au 14 nov. 2026 ». */
export function formatEventRange(event, locale = 'fr') {
    const start = event.starts_at;
    const end = event.ends_at;
    const day = (iso) => formatDate(iso, locale, { day: 'numeric', month: 'short', year: 'numeric' });
    const to = locale === 'en' ? 'to' : 'à';

    if (!end || day(start) === day(end)) {
        if (event.is_all_day) {
            return day(start);
        }

        return end ? `${day(start)}, ${formatTime(start, locale)} ${to} ${formatTime(end, locale)}` : `${day(start)}, ${formatTime(start, locale)}`;
    }

    return `${day(start)} ${locale === 'en' ? 'to' : 'au'} ${day(end)}`;
}

/** Éléments de date pour les pastilles calendrier (jour + mois abrégé). */
export function dateParts(iso, locale = 'fr') {
    return {
        day: formatDate(iso, locale, { day: '2-digit' }),
        month: formatDate(iso, locale, { month: 'short' }).replace('.', ''),
        weekday: formatDate(iso, locale, { weekday: 'short' }).replace('.', ''),
    };
}
